import { test, expect } from '@playwright/test';
test('editor, examples, generated C++, and source download work', async ({ page }) => {
  const errors: string[] = [];
  page.on('pageerror', (error) => errors.push(error.message));
  await page.goto('/');
  await expect(
    page.getByRole('heading', { name: 'From an idea to a blinking LED.' }),
  ).toBeVisible();
  await expect(page.locator('.monaco-editor .view-lines')).toBeVisible();
  await expect(page.getByRole('button', { name: '▷ Build', exact: true })).toBeEnabled();
  await expect(page.getByRole('button', { name: '↥ Flash board', exact: true })).toBeDisabled();
  await page.getByRole('button', { name: 'Functions', exact: false }).click();
  await expect(page.locator('.view-lines')).toContainText('twice');
  await page.locator('.editor-tabs').getByRole('button', { name: 'main.cpp', exact: true }).click();
  await expect(page.locator('.view-lines')).toContainText('Generated by EspLang');
  const download = page.waitForEvent('download');
  await page.getByRole('button', { name: '↓ Save C++', exact: true }).click();
  expect((await download).suggestedFilename()).toBe('main.cpp');
  await page
    .locator('.editor-tabs')
    .getByRole('button', { name: 'E program.esp', exact: true })
    .click();
  await page.getByRole('button', { name: 'PWM fade', exact: false }).click();
  await expect(page.locator('.view-lines')).toContainText('pwmWrite');
  await page.screenshot({ path: '.verification/ide-desktop.png', fullPage: true });
  expect(errors).toEqual([]);
});
test('invalid GPIOs produce markers and block builds; source survives reload', async ({ page }) => {
  await page.goto('/');
  await expect(page.locator('.monaco-editor .view-lines')).toBeVisible();
  await page.locator('.monaco-editor textarea').focus();
  await page.keyboard.press('ControlOrMeta+A');
  await page.keyboard.insertText('setup {}\nloop { pinMode(34, OUTPUT); }');
  await expect(page.getByRole('button', { name: '▷ Build', exact: true })).toBeDisabled();
  await page.getByRole('button', { name: 'Problems', exact: false }).click();
  await expect(page.locator('.problems')).toContainText('GPIO 34 is input-only');
  await page.reload();
  await expect(page.locator('.view-lines')).toContainText('pinMode(34, OUTPUT)');
});
test('serial panel is usable and mobile layout fits the viewport', async ({ page }) => {
  await page.goto('/');
  await page.getByRole('button', { name: 'Serial monitor', exact: false }).click();
  await expect(page.getByLabel('Serial message')).toBeDisabled();
  await page.getByLabel('Serial baud rate').selectOption('921600');
  await expect(page.getByRole('button', { name: 'Open monitor', exact: true })).toBeEnabled();
  await page.setViewportSize({ width: 390, height: 844 });
  await expect(page.locator('.sidebar')).toBeHidden();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(
    true,
  );
  await page.screenshot({ path: '.verification/ide-mobile.png', fullPage: true });
});

import type { ProgramNode, Expression, Statement, BlockNode, ValueType } from './ast.js';
import { boards, type BoardId } from './boards.js';
import { constants } from './analyzer.js';
const cppType = (type: ValueType): string =>
  ({ int: 'int32_t', float: 'double', bool: 'bool', string: 'String', void: 'void' })[type];
const name = (s: string): string => `el_${s}`;
export function generate(program: ProgramNode, boardId: BoardId): string {
  const board = boards[boardId];
  const usedHardware = new Set<string>();
  function expr(e: Expression): string {
    switch (e.kind) {
      case 'Literal':
        return e.valueType === 'string'
          ? `String(${JSON.stringify(e.value).replace(/\\u0000/g, '\\000')})`
          : e.valueType === 'float'
            ? `${Number(e.value).toExponential(16)}`
            : String(e.value);
      case 'Identifier':
        return Object.hasOwn(constants, e.name) ? e.name : name(e.name);
      case 'UnaryExpr':
        return `(${e.operator}${expr(e.operand)})`;
      case 'BinaryExpr':
        return `(${expr(e.left)} ${e.operator} ${expr(e.right)})`;
      case 'HardwareCall':
        usedHardware.add(e.name);
        return `el_hw_${e.name}(${e.args.map(expr).join(', ')})`;
      case 'CallExpr':
        return `${name(e.name)}(${e.args.map(expr).join(', ')})`;
    }
  }
  const simple = (s: Statement): string =>
    s.kind === 'VariableDecl'
      ? `${cppType(s.valueType)} ${name(s.name)} = ${expr(s.initializer)}`
      : s.kind === 'Assign'
        ? `${name(s.name)} = ${expr(s.value)}`
        : '';
  function block(b: BlockNode, level: number, yieldLoop = false): string {
    return `{\n${b.statements.map((s) => statement(s, level + 1)).join('\n')}${yieldLoop ? `\n${'  '.repeat(level + 1)}delay(1);` : ''}\n${'  '.repeat(level)}}`;
  }
  function statement(s: Statement, level: number): string {
    const pad = '  '.repeat(level);
    let code: string;
    switch (s.kind) {
      case 'VariableDecl':
      case 'Assign':
        code = `${simple(s)};`;
        break;
      case 'Block':
        code = block(s, level);
        break;
      case 'PinConfig':
        code = `el_hw_pinMode(${expr(s.pin)}, ${expr(s.mode)});`;
        break;
      case 'ExprStatement':
        code = `${expr(s.expression)};`;
        break;
      case 'Return':
        code = `return${s.value ? ` ${expr(s.value)}` : ''};`;
        break;
      case 'If':
        code = `if (${expr(s.condition)}) ${block(s.then, level)}${s.otherwise ? ` else ${block(s.otherwise.kind === 'Block' ? s.otherwise : { kind: 'Block', statements: [s.otherwise], span: s.otherwise.span }, level)}` : ''}`;
        break;
      case 'While':
        code = `while (${expr(s.condition)}) ${block(s.body, level, true)}`;
        break;
      case 'For':
        code = `for (${simple(s.init)}; ${expr(s.condition)}; ${simple(s.update)}) ${block(s.body, level, true)}`;
        break;
    }
    return `${pad}#line ${s.span.start.line} "program.esp"\n${pad}${code}`;
  }
  const signature = (f: ProgramNode['functions'][number]): string =>
    `${cppType(f.returnType)} ${name(f.name)}(${f.params.map((p) => `${cppType(p.valueType)} ${name(p.name)}`).join(', ')})`;
  const globals = program.globals.map((g) => `${simple(g)};`).join('\n');
  const functions = program.functions
    .map((f) => `${signature(f)} ${block(f.body, 0)}`)
    .join('\n\n');
  const setup = program.setup.statements.map((s) => statement(s, 1)).join('\n');
  const loop = block(program.loop.body, 0, true);
  const wifi = usedHardware.has('wifiConnect'),
    http = usedHardware.has('httpGet');
  return `// Generated by EspLang. Arduino-ESP32 core 3.x.\n#include <Arduino.h>
${wifi || http ? '#include <WiFi.h>' : ''}
${http ? '#include <HTTPClient.h>' : ''}
#include <esp_arduino_version.h>
#if ESP_ARDUINO_VERSION_MAJOR < 3
#error EspLang requires Arduino-ESP32 core 3.x
#endif
static bool el_validPin(int pin, bool output = false) {
  const bool exists = ${board.pins
    .filter((p) => !board.reserved.includes(p))
    .map((p) => `pin == ${p}`)
    .join(' || ')};
  const bool inputOnly = ${board.inputOnly.map((p) => `pin == ${p}`).join(' || ') || 'false'};
  if (!exists || (output && inputOnly)) { Serial.println("EspLang: invalid GPIO operation"); return false; }
  return true;
}
static void el_hw_pinMode(int pin, int mode) {
  if (mode != INPUT && mode != OUTPUT && mode != INPUT_PULLUP && mode != INPUT_PULLDOWN) { Serial.println("EspLang: invalid pin mode"); return; }
  const bool needsOutput = mode != INPUT;
  if (el_validPin(pin, needsOutput)) pinMode(pin, mode);
}
static void el_hw_digitalWrite(int pin, int value) { if (el_validPin(pin, true) && (value == LOW || value == HIGH)) digitalWrite(pin, value); }
static int el_hw_digitalRead(int pin) { return el_validPin(pin) ? digitalRead(pin) : LOW; }
static bool el_pwmAttached[64] = {};
static void el_hw_pwmWrite(int pin, int duty) {
  if (!el_validPin(pin, true) || pin < 0 || pin >= 64 || duty < 0 || duty > 255) { Serial.println("EspLang: invalid PWM operation"); return; }
  if (!el_pwmAttached[pin]) { if (!ledcAttach(pin, 5000, 8)) { Serial.println("EspLang: PWM channel unavailable"); return; } el_pwmAttached[pin] = true; }
  ledcWrite(pin, duty);
}
static void el_hw_delay(int32_t ms) { if (ms >= 0) delay(static_cast<uint32_t>(ms)); }
template<typename T> static void el_hw_serialPrint(const T& value) { Serial.println(value); }
${
  wifi
    ? `static bool el_hw_wifiConnect(const String& ssid, const String& password) {
  WiFi.mode(WIFI_STA); WiFi.begin(ssid.c_str(), password.c_str());
  const uint32_t started = millis();
  while (WiFi.status() != WL_CONNECTED && millis() - started < 15000) delay(50);
  return WiFi.status() == WL_CONNECTED;
}`
    : ''
}
${
  http
    ? `static String el_hw_httpGet(const String& url) {
  if (WiFi.status() != WL_CONNECTED || !url.startsWith("http://")) { Serial.println("EspLang: httpGet requires WiFi and an http:// URL"); return String(""); }
  WiFiClient client; HTTPClient http; http.setConnectTimeout(5000); http.setTimeout(5000);
  if (!http.begin(client, url)) return String("");
  const int code = http.GET(); String result;
  if (code >= 200 && code < 300) { const int length = http.getSize(); if (length >= 0 && length <= 16384) result = http.getString(); else Serial.println("EspLang: HTTP response must have Content-Length <= 16384"); }
  else { Serial.print("EspLang: HTTP status "); Serial.println(code); }
  http.end(); return result;
}`
    : ''
}
${program.functions.map((f) => `${signature(f)};`).join('\n')}
${globals}
${functions}
void setup() { Serial.begin(115200);\n${setup}\n}
void loop() ${loop}
`;
}
